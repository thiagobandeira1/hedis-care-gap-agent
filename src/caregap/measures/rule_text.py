"""Rule text: the tagged, citable statement of every demo-grade measure rule.

``rules/json/<id>.json`` is GENERATED by ``scripts/sync_rule_text.py`` from P2's committed
public-domain corpus (CMS 2026 Part C & D Star Ratings Technical Notes) plus cite-only public
URLs (NCQA / eCQI summaries, the public ACC/AHA statin-intensity table) and this repo's SPEC
(section 2). Never edit the JSON by hand; re-run the script.

Every element carries one tag (ADR-0005):

``quoted``
    ``text`` is a verbatim public sentence (``quote == text``); the citation names the corpus
    document and page the sentence was lifted from.
``demo_choice``
    a parameter this demo fixed (window, code set, status rule, proxy); ``rationale`` says WHY.
``not_representable``
    a public criterion Synthea / P6 cannot evidence; ``quote`` keeps the public wording so the
    coverage table can show exactly what is missing.

Element ``kind`` mirrors the SPEC section 2 table columns: ``denominator``, ``numerator``,
``exclusion`` (each with a ``coverage`` verdict), ``timeline`` (measurement-year mechanics), and
``coverage`` (escalation hints E1-E7: things the engine can only surface for a human).

The engine never reads these files. They feed the validator packet, the UI cards,
``/v1/measures``, and ``docs/MEASURES.md``.
"""

import json
import re
from datetime import date
from functools import cache
from importlib import resources
from importlib.resources.abc import Traversable
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from caregap.measures.ids import ALL_MEASURES, CONFORMANCE_NOTICE, MeasureId
from caregap.measures.models import Coverage

ElementKind = Literal["denominator", "numerator", "exclusion", "timeline", "coverage"]
ElementSource = Literal["quoted", "demo_choice", "not_representable"]
LicensePosture = Literal["us_gov_public_domain", "public_web_cite_only", "project_spec"]

_ELEMENT_ID = re.compile(r"^(?P<measure>[a-z]{3})/(?P<kind>[a-z]+)/(?P<slug>[a-z0-9_]+)$")


class RuleSource(BaseModel):
    """One citable source. ``page`` is the corpus page (PDF page index) for TN sources."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    doc_id: str
    title: str
    url: str
    page: int | None = None
    retrieval_date: date
    license_posture: LicensePosture
    note: str | None = None


class RuleElement(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    """``<measure>/<kind>/<slug>``, e.g. ``cbp/denominator/age``."""
    kind: ElementKind
    text: str
    source: ElementSource
    citation: str
    """``<doc_id>`` optionally followed by a locator, e.g. ``cms-tn-2026 p.56``."""
    quote: str | None = None
    """Verbatim public wording. Required (and equal to ``text``) when ``source == quoted``."""
    rationale: str | None = None
    """WHY the demo fixed this parameter / cannot represent this criterion."""
    coverage: Coverage | None = None
    """Required for ``exclusion`` elements: observable | partial | not_representable."""

    @property
    def doc_id(self) -> str:
        return self.citation.split(" ", 1)[0]

    @model_validator(mode="after")
    def _check(self) -> "RuleElement":
        m = _ELEMENT_ID.match(self.id)
        if m is None:
            raise ValueError(f"element id {self.id!r} is not <measure>/<kind>/<slug>")
        if m.group("kind") != self.kind:
            raise ValueError(f"element id {self.id!r} does not match kind {self.kind!r}")
        if not self.text.strip():
            raise ValueError(f"element {self.id!r} has empty text")
        if self.source == "quoted":
            if self.quote is None or self.quote != self.text:
                raise ValueError(f"quoted element {self.id!r} must carry quote == text")
        elif self.rationale is None or not self.rationale.strip():
            raise ValueError(f"{self.source} element {self.id!r} needs a rationale")
        if self.kind == "exclusion" and self.coverage is None:
            raise ValueError(f"exclusion element {self.id!r} needs a coverage verdict")
        if self.source == "not_representable" and self.coverage == "observable":
            raise ValueError(f"not_representable element {self.id!r} cannot be observable")
        return self


class TnSection(BaseModel):
    """A verbatim Technical Notes section (public domain) carried for display."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    heading: str
    text: str
    page: int


class NormativeQuote(BaseModel):
    """The public one-sentence definition of the measure (Metric + Description)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    metric: str
    description: str | None = None
    citation: str
    conflict: str | None = None
    """Set when the public Description and Metric disagree (e.g. BCS 50-74 vs 52-74)."""


class RuleText(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    measure_id: MeasureId
    star_id: str | None
    name: str
    rule_version: str
    sources: list[RuleSource] = Field(min_length=1)
    elements: list[RuleElement] = Field(min_length=1)
    normative_quote: NormativeQuote | None = None
    tn_sections: dict[str, TnSection] | None = None
    conformance: str

    @model_validator(mode="after")
    def _check(self) -> "RuleText":
        if self.conformance != CONFORMANCE_NOTICE:
            raise ValueError(f"conformance must be exactly {CONFORMANCE_NOTICE!r}")
        doc_ids = [s.doc_id for s in self.sources]
        if len(set(doc_ids)) != len(doc_ids):
            raise ValueError("duplicate source doc_id")
        ids = [e.id for e in self.elements]
        if len(set(ids)) != len(ids):
            raise ValueError("duplicate element id")
        prefix = f"{self.measure_id.lower()}/"
        for e in self.elements:
            if not e.id.startswith(prefix):
                raise ValueError(f"element {e.id!r} does not belong to {self.measure_id}")
            if e.doc_id not in doc_ids:
                raise ValueError(f"element {e.id!r} cites unknown source {e.doc_id!r}")
        if (
            self.normative_quote is not None
            and self.normative_quote.citation.split(" ", 1)[0] not in doc_ids
        ):
            raise ValueError("normative_quote cites an unknown source")
        return self

    def elements_of(self, kind: ElementKind) -> list[RuleElement]:
        return [e for e in self.elements if e.kind == kind]

    def element(self, element_id: str) -> RuleElement:
        for e in self.elements:
            if e.id == element_id:
                return e
        raise KeyError(f"unknown element {element_id!r} in {self.measure_id}")

    @property
    def coverage_table(self) -> dict[str, Coverage]:
        """Every public exclusion criterion -> observable | partial | not_representable."""
        return {e.id: e.coverage for e in self.elements_of("exclusion") if e.coverage is not None}


def rule_text_dir() -> Traversable:
    return resources.files("caregap.measures.rules") / "json"


def rule_text_path(measure_id: MeasureId) -> Traversable:
    return rule_text_dir() / f"{measure_id.lower()}.json"


@cache
def load_rule_text(measure_id: MeasureId) -> RuleText:
    raw = json.loads(rule_text_path(measure_id).read_text(encoding="utf-8"))
    text = RuleText.model_validate(raw)
    if text.measure_id != measure_id:
        raise ValueError(f"{measure_id.lower()}.json declares measure_id {text.measure_id!r}")
    return text


def all_rule_texts() -> dict[MeasureId, RuleText]:
    return {m: load_rule_text(m) for m in ALL_MEASURES}
