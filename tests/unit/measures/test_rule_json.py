@pytest.mark.parametrize("measure_id", ALL_MEASURES)
def test_json_validates_against_model(measure_id: MeasureId) -> None:
    text = RuleText.model_validate(_raw(measure_id))
    assert text.measure_id == measure_id
    assert text.star_id == STAR_IDS[measure_id]
    assert text.name == MEASURE_NAMES[measure_id]
    assert text.rule_version == f"{measure_id.lower()}-v1"
    assert load_rule_text(measure_id) == text


@pytest.mark.parametrize("measure_id", ALL_MEASURES)
def test_conformance_string_exact(measure_id: MeasureId) -> None:
    assert _raw(measure_id)["conformance"] == "demo-grade; HEDIS-aligned; not NCQA-certified"
    assert load_rule_text(measure_id).conformance == CONFORMANCE_NOTICE


def test_all_rule_texts_covers_every_measure() -> None:
    assert tuple(all_rule_texts()) == ALL_MEASURES


@pytest.mark.parametrize("measure_id", ALL_MEASURES)
def test_every_kind_present_and_tags_well_formed(measure_id: MeasureId) -> None:
    text = load_rule_text(measure_id)
    kinds = {e.kind for e in text.elements}
    assert kinds == {"denominator", "numerator", "exclusion", "timeline", "coverage"}
    for e in text.elements:
        assert e.id.startswith(f"{measure_id.lower()}/{e.kind}/")
        if e.source == "quoted":
            assert e.quote == e.text
        else:
            assert e.rationale, f"{e.id}: demo/not_representable elements must say WHY"
        if e.kind == "exclusion":
            assert e.coverage in {"observable", "partial", "not_representable"}
    assert {e.coverage for e in text.elements_of("exclusion")} <= {
        "observable",
        "partial",
        "not_representable",
    }


@pytest.mark.parametrize("measure_id", TN_MEASURES)
def test_tn_measures_cite_the_public_domain_corpus(measure_id: MeasureId) -> None:
    text = load_rule_text(measure_id)
    tn = next(s for s in text.sources if s.doc_id == "cms-tn-2026")
    assert tn.license_posture == "us_gov_public_domain"
    assert tn.page is not None
    assert text.normative_quote is not None
    assert text.tn_sections is not None
    assert set(text.tn_sections) == {"description", "metric", "exclusions", "data_time_frame"}
    quoted = [e for e in text.elements if e.source == "quoted"]
    assert quoted, "a Technical Notes measure must quote its public wording"
    for e in quoted:
        doc_id, page = _citation(e.citation)
        assert doc_id == "cms-tn-2026" and page is not None, e.id


