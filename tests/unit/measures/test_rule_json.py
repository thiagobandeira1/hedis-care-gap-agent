def _raw(measure_id: MeasureId) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(rule_text_path(measure_id).read_text(encoding="utf-8"))
    return data


@pytest.fixture(scope="module")
def corpus() -> dict[str, Any]:
    if not CORPUS.exists():
        pytest.skip(
            f"P2 corpus not checked out at {CORPUS} (set CAREGAP_P2_CORPUS); "
            "verbatim-quote and generator-drift checks need it"
        )
    data: dict[str, Any] = json.loads(CORPUS.read_text(encoding="utf-8"))
    return data


@pytest.fixture(scope="module")
def generator(corpus: dict[str, Any]) -> ModuleType:
    spec = importlib.util.spec_from_file_location("sync_rule_text", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolve postponed annotations through sys.modules[cls.__module__].
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _sections(corpus: dict[str, Any], star_id: str, page: int | None) -> list[str]:
    for m in corpus["measures"]:
        if m["measure_id"] == star_id:
            return [str(s["text"]) for s in m["sections"] if page is None or s.get("page") == page]
    return []


def _citation(text: str) -> tuple[str, int | None]:
    doc_id, _, locator = text.partition(" ")
    page = int(locator[2:]) if locator.startswith("p.") else None
    return doc_id, page


def _quotes(text: RuleText) -> Iterator[tuple[str, str, str]]:
    """(label, citation, verbatim string) for everything that claims to be public wording."""
    for e in text.elements:
        if e.quote is not None:
            yield e.id, e.citation, e.quote
    if text.normative_quote is not None:
        yield "normative_quote.metric", text.normative_quote.citation, text.normative_quote.metric
        if text.normative_quote.description:
            yield (
                "normative_quote.description",
                text.normative_quote.citation,
                text.normative_quote.description,
            )
    if text.tn_sections:
        for key, section in text.tn_sections.items():
            yield f"tn_sections.{key}", f"cms-tn-2026 p.{section.page}", section.text


