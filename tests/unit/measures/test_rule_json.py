@pytest.mark.parametrize("measure_id", ALL_MEASURES)
def test_every_spec_table_exclusion_has_an_element(measure_id: MeasureId) -> None:
    text = load_rule_text(measure_id)
    by_slug = {e.id.rsplit("/", 1)[1]: e for e in text.elements_of("exclusion")}
    for slug, (tag, coverage) in SPEC_EXCLUSIONS[measure_id].items():
        assert slug in by_slug, f"{measure_id}: SPEC exclusion {slug!r} has no element"
        assert by_slug[slug].source == tag, f"{measure_id}/{slug}: tag"
        assert by_slug[slug].coverage == coverage, f"{measure_id}/{slug}: coverage"
    assert text.coverage_table.keys() == {e.id for e in text.elements_of("exclusion")}


@pytest.mark.parametrize("measure_id", ALL_MEASURES)
def test_every_spec_table_escalation_has_a_coverage_element(measure_id: MeasureId) -> None:
    slugs = {e.id.rsplit("/", 1)[1] for e in load_rule_text(measure_id).elements_of("coverage")}
    assert slugs == SPEC_ESCALATIONS[measure_id]


